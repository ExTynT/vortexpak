"""VortexPak roadmap: docs/roadmap.json is the single source of truth; the README
section between the roadmap markers is generated from it.

Usage:
    python tools/roadmap.py                      regenerate the README section
    python tools/roadmap.py --check              exit 1 when the README is stale (CI)
    python tools/roadmap.py done M9 [--date YYYY-MM-DD] [--evidence PATH]
    python tools/roadmap.py set M13 active       statuses: done, active, next, planned
"""

from __future__ import annotations

import argparse
import datetime as dt
import html
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "docs" / "roadmap.json"
README = ROOT / "README.md"
START = "<!-- roadmap:start: generated by tools/roadmap.py from docs/roadmap.json, edit there -->"
END = "<!-- roadmap:end -->"
BLOCK = re.compile(r"<!-- roadmap:start.*?-->.*?<!-- roadmap:end -->", re.S)
ICONS = {"done": "✅", "active": "🚧", "next": "🔜", "planned": "⬜"}
LABELS = {"done": "done", "active": "in progress", "next": "next", "planned": "planned"}
STYLES = {
    "done": "fill:#2da44e,stroke:#1a7f37,color:#ffffff",
    "active": "fill:#bf8700,stroke:#9a6700,color:#ffffff",
    "next": "fill:#0969da,stroke:#0550ae,color:#ffffff",
    "planned": "fill:#f6f8fa,stroke:#8c959f,color:#57606a,stroke-dasharray:4 3",
}
ORDER = ("id", "title", "goal", "status", "date", "evidence")
STAR_KEYS = ("title", "statement", "gates", "evidence")
GATE_KEYS = ("gate", "target", "today")
FENCE = chr(96) * 3
TICK = chr(96)


def load(path: Path = DATA) -> Dict[str, Any]:
    data: Dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def save(data: Dict[str, Any], path: Path = DATA) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def milestones(data: Dict[str, Any]) -> List[Dict[str, Any]]:
    return [m for phase in data["phases"] for m in phase["milestones"]]


def _evidence_ok(evidence: Any, root: Path) -> bool:
    if isinstance(evidence, str) and re.match(r"https?://", evidence):
        return True
    return isinstance(evidence, str) and bool(evidence) and (root / evidence).exists()


def _validate_north_star(star: Any, root: Path) -> List[str]:
    if not isinstance(star, dict):
        return ["north_star must be an object"]
    errors = [f"north_star: unknown keys {sorted(set(star) - set(STAR_KEYS))}"] if set(star) - set(STAR_KEYS) else []
    for key in ("title", "statement"):
        if not isinstance(star.get(key), str) or not star[key].strip():
            errors.append(f"north_star: missing {key}")
    gates = star.get("gates")
    if not isinstance(gates, list) or not gates:
        errors.append("north_star: needs a non-empty gates list")
    else:
        for i, gate in enumerate(gates, 1):
            if not isinstance(gate, dict) or set(gate) != set(GATE_KEYS) or not all(
                isinstance(gate[k], str) and gate[k].strip() for k in GATE_KEYS
            ):
                errors.append(f"north_star gate {i}: needs exactly non-empty {', '.join(GATE_KEYS)}")
    if "evidence" in star and not _evidence_ok(star["evidence"], root):
        errors.append(f"north_star: evidence {star['evidence']!r} does not exist")
    return errors


def validate(data: Dict[str, Any], root: Path = ROOT) -> None:
    """Raise ValueError listing every inconsistency (ids, statuses, dates, evidence)."""
    phases = data.get("phases")
    if not isinstance(phases, list) or not phases:
        raise ValueError("roadmap needs a non-empty 'phases' list")
    errors: List[str] = []
    if set(data) - {"north_star", "phases"}:
        errors.append(f"unknown top-level keys {sorted(set(data) - {'north_star', 'phases'})}")
    if "north_star" in data:
        errors += _validate_north_star(data["north_star"], root)
    seen = set()
    for phase in phases:
        if not str(phase.get("title", "")).strip() or not phase.get("milestones"):
            errors.append("every phase needs a title and at least one milestone")
            continue
        for m in phase["milestones"]:
            mid = m.get("id")
            if not isinstance(mid, str) or not re.fullmatch(r"M\d+", mid):
                errors.append(f"bad milestone id {mid!r} (expected M<number>)")
            elif mid in seen:
                errors.append(f"duplicate milestone id {mid}")
            seen.add(mid)
            unknown = sorted(set(m) - set(ORDER))
            if unknown:
                errors.append(f"{mid}: unknown keys {unknown}")
            for key in ("title", "goal"):
                if not isinstance(m.get(key), str) or not m[key].strip():
                    errors.append(f"{mid}: missing {key}")
            status = m.get("status")
            if status not in ICONS:
                errors.append(f"{mid}: status must be one of {', '.join(ICONS)}")
            if status == "done":
                try:
                    dt.date.fromisoformat(str(m.get("date")))
                except ValueError:
                    errors.append(f"{mid}: done needs an ISO date (YYYY-MM-DD)")
            elif "date" in m:
                errors.append(f"{mid}: only done milestones carry a date")
            evidence = m.get("evidence")
            if evidence is not None and not _evidence_ok(evidence, root):
                errors.append(f"{mid}: evidence {evidence!r} does not exist")
    if errors:
        raise ValueError("invalid roadmap:\n  " + "\n  ".join(errors))


def _label(text: str) -> str:
    return text.replace('"', "#quot;")


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render_north_star(star: Dict[str, Any]) -> List[str]:
    out = [f"### 🎯 North Star: {star['title']}", "", f"> **{star['statement']}**", "",
           "| Gate | Target | Today |", "|---|---|---|"]
    out += [f"| **{_cell(g['gate'])}** | {_cell(g['target'])} | {_cell(g['today'])} |" for g in star["gates"]]
    out.append("")
    if star.get("evidence"):
        out += [f"Every gate must hold at once, in one reproducible run. [Baseline evidence]({star['evidence']})", ""]
    return out


def render(data: Dict[str, Any]) -> str:
    """The README block: progress, Mermaid diagram and per-phase checklists."""
    items = milestones(data)
    done = sum(m["status"] == "done" for m in items)
    filled = round(20 * done / len(items))
    out = [START, ""]
    if data.get("north_star"):
        out += render_north_star(data["north_star"])
    out += [
        f"**Progress:** {done} of {len(items)} milestones done ({round(100 * done / len(items))} %) "
        f"{TICK}{'█' * filled}{'░' * (20 - filled)}{TICK}",
        "",
        FENCE + "mermaid",
        "flowchart LR",
    ]
    out += [f"  classDef {status} {style}" for status, style in STYLES.items()]
    for i, phase in enumerate(data["phases"], 1):
        out += [f'  subgraph P{i}["{i} · {_label(phase["title"])}"]', "    direction TB"]
        for m in phase["milestones"]:
            label = f'{ICONS[m["status"]]} {m["id"]} · {_label(m["title"])}'
            out.append(f'    {m["id"]}["{label}"]:::{m["status"]}')
        out.append("  end")
    out.append("  " + " --> ".join(f"P{i}" for i in range(1, len(data["phases"]) + 1)))
    out += [FENCE, "", " · ".join(f"{ICONS[s]} {LABELS[s]}" for s in ICONS), ""]
    for i, phase in enumerate(data["phases"], 1):
        ms = phase["milestones"]
        n_done = sum(m["status"] == "done" for m in ms)
        complete = n_done == len(ms)
        started = any(m["status"] != "planned" for m in ms)
        badge = " ✅" if complete else (" 🚧" if n_done or any(m["status"] == "active" for m in ms) else "")
        out.append("<details open>" if started and not complete else "<details>")
        out.append(
            f"<summary><b>Phase {i} · {html.escape(phase['title'])}</b> · {n_done}/{len(ms)}{badge}</summary>"
        )
        out.append("")
        for m in ms:
            box = "x" if m["status"] == "done" else " "
            line = f"- [{box}] **{m['id']} · {m['title']}** — {m['goal']}"
            if m["status"] == "done":
                line += f" *({m['date']})*"
            else:
                line += f" {ICONS[m['status']]} *{LABELS[m['status']]}*"
            if m.get("evidence"):
                line += f" · [evidence]({m['evidence']})"
            out.append(line)
        out += ["", "</details>", ""]
    out.append(
        f"Mark progress with {TICK}python tools/roadmap.py done M9{TICK} (records today's date) or "
        f"{TICK}python tools/roadmap.py set M13 active{TICK}; add or reword milestones in "
        f"{TICK}docs/roadmap.json{TICK} and rerun {TICK}python tools/roadmap.py{TICK}. "
        "CI fails when this section is out of date."
    )
    out.append(END)
    return "\n".join(out)


def sync(
    data_path: Path = DATA, readme_path: Path = README, check: bool = False, root: Optional[Path] = None
) -> bool:
    """Regenerate the README block (unless check). Returns True if it was already current."""
    data = load(data_path)
    validate(data, root or readme_path.parent)
    with open(readme_path, encoding="utf-8", newline="") as f:
        raw = f.read()
    text = raw.replace("\r\n", "\n")
    if len(BLOCK.findall(text)) != 1:
        raise ValueError(f"{readme_path.name} needs exactly one roadmap:start / roadmap:end marker pair")
    new = BLOCK.sub(lambda _: render(data), text)
    if new == text:
        return True
    if not check:
        with open(readme_path, "w", encoding="utf-8", newline="") as f:
            f.write(new.replace("\n", "\r\n") if "\r\n" in raw else new)
    return False


def set_status(
    data: Dict[str, Any], mid: str, status: str, date: Optional[str] = None, evidence: Optional[str] = None
) -> Dict[str, Any]:
    if status not in ICONS:
        raise ValueError(f"status must be one of {', '.join(ICONS)}")
    for m in milestones(data):
        if m["id"] == mid:
            m["status"] = status
            if status == "done":
                m["date"] = date or dt.date.today().isoformat()
            else:
                m.pop("date", None)
            if evidence is not None:
                m["evidence"] = evidence
            ordered = {k: m[k] for k in ORDER if k in m}
            m.clear()
            m.update(ordered)
            return m
    raise ValueError(f"unknown milestone {mid}; known: {', '.join(x['id'] for x in milestones(data))}")


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when README.md is out of date")
    sub = ap.add_subparsers(dest="cmd")
    p_done = sub.add_parser("done", help="mark a milestone done (date defaults to today)")
    p_done.add_argument("id")
    p_done.add_argument("--date")
    p_done.add_argument("--evidence", help="repo path or URL proving the milestone")
    p_set = sub.add_parser("set", help="change a milestone status")
    p_set.add_argument("id")
    p_set.add_argument("status", choices=list(ICONS))
    p_set.add_argument("--evidence")
    args = ap.parse_args(argv)
    try:
        if args.cmd:
            data = load(DATA)
            status = "done" if args.cmd == "done" else args.status
            m = set_status(data, args.id.upper(), status, getattr(args, "date", None), args.evidence)
            validate(data, ROOT)
            save(data, DATA)
            print(f"{m['id']}: {status}" + (f" ({m['date']})" if status == "done" else ""))
        fresh = sync(DATA, README, check=args.check, root=ROOT)
    except ValueError as exc:
        print(f"roadmap: {exc}", file=sys.stderr)
        return 1
    if args.check and not fresh:
        print("README.md roadmap is out of date: run python tools/roadmap.py", file=sys.stderr)
        return 1
    items = milestones(load(DATA))
    done = sum(m["status"] == "done" for m in items)
    print(f"README roadmap {'up to date' if fresh else 'updated'}: {done}/{len(items)} milestones done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
